/**
 * Image-to-video adapter.
 * 1. Custom local/remote img2vid endpoint (ComfyUI Wan 2.2 / FramePack / LTX-Video).
 * 2. Zero-GPU browser WebM motion clip via Canvas + MediaRecorder (works 100% free & offline).
 * 3. Honest multi-frame sequence fallback if MediaRecorder is unavailable.
 */

import { getMediaSettings } from "./mediaSettings";
import { canRenderBrowserClip, MOTION_PRESETS, renderBrowserWebmClip } from "./browserClip";
import { fetchWorkerImage } from "./imageWorker";
import { fetchWithRetry } from "./netRetry";

/** Generate verified frame sequence using the image worker (stops cleanly on quota). */
export async function generateFreeFrames(
  baseImageUrl: string,
  motionPrompt: string,
  count = 4,
): Promise<string[]> {
  const frames: string[] = [];
  for (let i = 0; i < count; i++) {
    const prompt = `${motionPrompt}, frame ${i + 1} of sequence, slight natural movement, photorealistic`;
    const res = await fetchWorkerImage(prompt, { steps: 6, seed: (Date.now() % 100000) + i });
    if (!res.ok) break;
    frames.push(res.url);
  }
  return frames.length > 0 ? frames : baseImageUrl ? [baseImageUrl] : [];
}

export type VideoClipResult = {
  /** True MP4/WebM URL when available */
  videoUrl: string | null;
  /** Always available still frames */
  frames: string[];
  /** Honest label for UI */
  mode: "mp4" | "webm" | "sequence";
  note: string;
};

/** Build a Pollinations-style video GET URL when the user supplies an explicit Pollinations key. */
export function buildPollinationsVideoUrl(
  imageUrl: string,
  motionPrompt: string,
  opts?: { duration?: number; seed?: number },
): string {
  const settings = getMediaSettings();
  const duration = opts?.duration ?? 3;
  const seed = opts?.seed ?? 42;
  const prompt = encodeURIComponent(
    `${motionPrompt}, smooth motion, photorealistic, adult content allowed`,
  );
  const params = new URLSearchParams({
    model: "wan",
    duration: String(duration),
    seed: String(seed),
    image: imageUrl,
  });
  if (settings.pollinationsKey) params.set("key", settings.pollinationsKey);
  return `https://gen.pollinations.ai/video/${prompt}?${params.toString()}`;
}

/** Real call to Pollinations video. Retries the 429s the free tier throws. */
export async function requestPollinationsVideo(
  imageUrl: string,
  motionPrompt: string,
  opts?: { duration?: number; seed?: number; signal?: AbortSignal },
): Promise<string> {
  const url = buildPollinationsVideoUrl(imageUrl, motionPrompt, opts);
  const res = await fetchWithRetry(
    url,
    { method: "GET" },
    { label: "Pollinations video", timeoutMs: 180_000, attempts: 3, signal: opts?.signal },
  );
  const type = res.headers.get("content-type") || "";
  if (type.startsWith("video/")) {
    return URL.createObjectURL(await res.blob());
  }
  const data = (await res.json().catch(() => ({}))) as { url?: string; videoUrl?: string };
  const out = data.videoUrl || data.url;
  if (out) return out;
  throw new Error("Pollinations returned no playable video");
}

/** Call custom img2vid if configured; otherwise render a browser WebM motion clip or return sequence frames. */
export async function requestImg2Vid(
  imageUrl: string,
  motionPrompt: string,
  frames: string[],
): Promise<VideoClipResult> {
  const settings = getMediaSettings();
  let backendError = "";

  if (settings.img2vidUrl) {
    const ctrl = new AbortController();
    const timeout = setTimeout(() => ctrl.abort(), 120_000);
    try {
      const res = await fetch(settings.img2vidUrl, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          image: imageUrl,
          imageUrl,
          prompt: motionPrompt,
          duration: 5,
          durationSec: 5,
        }),
        signal: ctrl.signal,
      });
      if (!res.ok) {
        throw new Error(`Video provider returned HTTP ${res.status}`);
      }
      const contentType = res.headers.get("content-type") || "";
      if (contentType.startsWith("video/")) {
        const video = await res.blob();
        if (!video.size) throw new Error("Video provider returned an empty file");
        return {
          videoUrl: URL.createObjectURL(video),
          frames,
          mode: contentType.includes("webm") ? "webm" : "mp4",
          note: "Generated by configured AI video model",
        };
      }
      const data = (await res.json()) as {
        videoUrl?: string;
        url?: string;
        video?: string;
        output?: string;
        error?: string;
      };
      const url = data.videoUrl || data.url || data.video || data.output;
      if (url && /^(https?:\/\/|blob:|data:video\/)/i.test(url)) {
        return {
          videoUrl: url,
          frames,
          mode: /\.webm(?:$|[?#])/i.test(url) ? "webm" : "mp4",
          note: "Generated by configured AI video model",
        };
      }
      backendError = data.error || "Video provider returned no playable video";
    } catch (err) {
      backendError = err instanceof Error ? err.message : "Video provider failed";
    } finally {
      clearTimeout(timeout);
    }
  }

  if (!backendError) {
    try {
      const videoUrl = await requestPollinationsVideo(imageUrl, motionPrompt, { duration: 5 });
      return { videoUrl, frames, mode: "mp4", note: "Generated by Pollinations Wan" };
    } catch (err) {
      backendError = err instanceof Error ? err.message : "Pollinations video failed";
    }
  }

  // Browser recording is only movement of a still. Never call it a generated
  // character video or silently claim the AI provider succeeded.
  const sourceStill = imageUrl || frames[0] || "";
  if (sourceStill && canRenderBrowserClip()) {
    try {
      const preset = /pan|side|walk|turn/i.test(motionPrompt)
        ? MOTION_PRESETS[1]
        : /up|reveal|rise|body/i.test(motionPrompt)
          ? MOTION_PRESETS[2]
          : MOTION_PRESETS[0];
      const webmUrl = await renderBrowserWebmClip(sourceStill, preset, 3000);
      if (webmUrl) {
        return {
          videoUrl: webmUrl,
          frames,
          mode: "webm",
          note: backendError
            ? `Animated still only (AI video backend failed: ${backendError})`
            : "Animated still (pan/zoom), not generated AI video",
        };
      }
    } catch {
      // Fall back to still frames on browsers without MediaRecorder.
    }
  }

  return {
    ...sequenceOnlyResult(frames),
    note: backendError
      ? `AI video unavailable: ${backendError}`
      : "No AI video backend or browser motion renderer available",
  };
}

export function sequenceOnlyResult(frames: string[]): VideoClipResult {
  return {
    videoUrl: null,
    frames,
    mode: "sequence",
    note: "Frame sequence (not a real MP4) — set Advanced → img2vid for true clips",
  };
}

