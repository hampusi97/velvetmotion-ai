import assert from "node:assert/strict";
import { activeStreak, claimDaily, DAILY_CREDITS, dayKey, emptyProgress, parseProgress } from "../lib/progress";
import { parseChatHistory } from "../lib/chat-history";

const firstDay = new Date(2026, 10, 9, 23, 59);
const first = claimDaily(emptyProgress(), firstDay);
assert.equal(first.credits, DAILY_CREDITS);
assert.equal(first.streak, 1);
assert.equal(first.lastClaim, dayKey(firstDay));
assert.deepEqual(claimDaily(first, firstDay), first, "Repeated claims grant no additional credits");
const restored = parseProgress(JSON.stringify(first));
assert.deepEqual(claimDaily(restored, firstDay), first, "Reloading preserves the claim guard");
const next = claimDaily(first, new Date(2026, 10, 10, 0, 1));
assert.equal(next.credits, DAILY_CREDITS * 2);
assert.equal(next.streak, 2, "Midnight starts the next calendar day");
assert.deepEqual(claimDaily(next, firstDay), next, "Turning the clock back grants no credits");
assert.equal(claimDaily(next, new Date(2026, 10, 12)).streak, 1, "A missed day resets the streak");
assert.equal(activeStreak(next, new Date(2026, 10, 12)), 0);
assert.equal(activeStreak(next, new Date(2026, 10, 11)), 2);
const spring = claimDaily(emptyProgress(), new Date(2026, 2, 7, 23, 59));
assert.equal(claimDaily(spring, new Date(2026, 2, 8, 23, 30)).streak, 2, "Calendar streaks survive DST");
assert.equal(claimDaily(claimDaily(emptyProgress(), new Date(2026, 11, 31)), new Date(2027, 0, 1)).streak, 2);
assert.deepEqual(parseProgress("bad JSON"), emptyProgress());
assert.deepEqual(parseProgress("[]"), emptyProgress());
const invalid = parseProgress(JSON.stringify({ credits: -1, streak: 2.5, lastClaim: "2026-02-31", favoriteIds: ["a", "a", 3], nightMode: "true", lastSession: { characterId: "a", romanceMode: false, updatedAt: "invalid" } }));
assert.deepEqual(invalid, { ...emptyProgress(), favoriteIds: ["a"] });
const saved = { ...next, favoriteIds: ["sample"], nightMode: true, lastSession: { characterId: "sample", romanceMode: false, updatedAt: firstDay.toISOString() } };
assert.deepEqual(parseProgress(JSON.stringify(saved)), saved);
assert.deepEqual(parseChatHistory("null"), []);
assert.deepEqual(parseChatHistory("broken"), []);
assert.deepEqual(parseChatHistory(JSON.stringify([{ role: "system", content: "invalid" }, { role: "user", content: "Hello" }, null])), [{ role: "user", content: "Hello" }]);
assert.equal(parseChatHistory(JSON.stringify(Array.from({ length: 101 }, (_, i) => ({ role: "user", content: String(i) })))).length, 100);
console.log("ok: daily claims, calendar streaks, storage validation, session round-trip, and chat restoration");
